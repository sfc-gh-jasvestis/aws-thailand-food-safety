-- CCP deviation risk scoring and CCP hold-hours forecast over the synthetic snapshot.
-- The data has no lot-level outcome history, so the model predicts a line's
-- P(CCP deviation in next 7 days) and reports out-of-time holdout metrics.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.DEVIATION_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, m.CATEGORY, m.AGE_YEARS,
       r.ATP_RLU, r.CHILL_TEMP_C,
       AVG(r.ATP_RLU) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS ATP_7D,
       SUM(r.DEVIATION_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS DEVIATIONS_30D,
       IFF(SUM(r.DEVIATION_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'FAIL', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.CCP_READINGS r JOIN RAW.PROCESSING_LINES m ON m.ID = r.ENTITY_ID
WHERE r.ROOT_CAUSE <> 'Plant power dip' OR r.DEVIATION_COUNT = 0;

-- Time-based split: train on older labelled days, hold out the most recent labelled 14 days.
CREATE VIEW ML.DEVIATION_TRAIN AS
SELECT CATEGORY, AGE_YEARS, ATP_RLU, CHILL_TEMP_C, ATP_7D, DEVIATIONS_30D, LABEL
FROM ML.DEVIATION_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.DEVIATION_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, AGE_YEARS, ATP_RLU, CHILL_TEMP_C, ATP_7D, DEVIATIONS_30D, LABEL
FROM ML.DEVIATION_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.DEVIATION_RISK_MODEL(
  INPUT_DATA => TABLE(ML.DEVIATION_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.DEVIATION_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.DEVIATION_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'AGE_YEARS', AGE_YEARS, 'ATP_RLU', ATP_RLU,
           'CHILL_TEMP_C', CHILL_TEMP_C, 'ATP_7D', ATP_7D, 'DEVIATIONS_30D', DEVIATIONS_30D)):probability:FAIL::FLOAT AS P
  FROM ML.DEVIATION_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'FAIL', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'FAIL', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'FAIL', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'FAIL', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per line (label unknown, so excluded from features).
CREATE TABLE ML.DEVIATION_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.DEVIATION_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.DEVIATION_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'AGE_YEARS', AGE_YEARS, 'ATP_RLU', ATP_RLU,
           'CHILL_TEMP_C', CHILL_TEMP_C, 'ATP_7D', ATP_7D, 'DEVIATIONS_30D', DEVIATIONS_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:FAIL::FLOAT, 4) AS DEVIATION_PROB_7D,
       CASE WHEN P:probability:FAIL::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:FAIL::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Plant-network CCP hold-hours forecast (14 days) from the daily series.
CREATE VIEW ML.DAILY_HOLD AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(HOLD_HOURS) AS HOLD_HOURS
FROM RAW.CCP_READINGS GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.HOLD_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_HOLD),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'HOLD_HOURS'
);

CREATE TABLE ML.HOLD_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, GREATEST(0, FORECAST) AS HOLD_HOURS,
       GREATEST(0, LOWER_BOUND) AS LOWER_BOUND, UPPER_BOUND
FROM TABLE(ML.HOLD_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
