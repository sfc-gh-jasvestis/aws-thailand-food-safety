-- On-demand snapshots. No automatic five-minute freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT pline.ID AS ENTITY_ID, pline.NAME AS ENTITY_NAME,
       pline.REGION, pline.CATEGORY, pline.STATUS,
       COUNT(*) AS EVENT_COUNT, SUM(observation.DEVIATION_COUNT) AS ALERT_COUNT,
       SUM(observation.OPERATING_HOURS) AS OPERATING_HOURS,
       SUM(observation.PLANNED_HOURS) AS PLANNED_HOURS,
       SUM(observation.HOLD_HOURS) AS HOLD_HOURS,
       SUM(observation.SANITATION_DUE) AS SANITATION_DUE, SUM(observation.SANITATION_DONE) AS SANITATION_DONE,
       SUM(observation.RELEASED_PACKS) AS RELEASED_PACKS, SUM(observation.TOTAL_PACKS) AS TOTAL_PACKS,
       100.0 * SUM(observation.OPERATING_HOURS) / NULLIF(SUM(observation.PLANNED_HOURS), 0) AS AVG_LINE_AVAILABILITY,
       SUM(observation.OPERATING_HOURS) / NULLIF(SUM(observation.DEVIATION_COUNT), 0) AS AVG_MTBD,
       100.0 * SUM(observation.SANITATION_DONE) / NULLIF(SUM(observation.SANITATION_DUE), 0) AS SANITATION_COMPLIANCE_PCT,
       100.0 * SUM(observation.RELEASED_PACKS) / NULLIF(SUM(observation.TOTAL_PACKS), 0) AS RELEASE_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.CCP_READINGS observation
JOIN RAW.PROCESSING_LINES pline ON pline.ID = observation.ENTITY_ID
GROUP BY pline.ID, pline.NAME, pline.REGION, pline.CATEGORY, pline.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(OPERATING_HOURS) AS OPERATING_HOURS, SUM(PLANNED_HOURS) AS PLANNED_HOURS,
       SUM(DEVIATION_COUNT) AS DEVIATION_COUNT,
       100.0 * SUM(OPERATING_HOURS) / NULLIF(SUM(PLANNED_HOURS), 0) AS AVG_LINE_AVAILABILITY,
       SUM(OPERATING_HOURS) / NULLIF(SUM(DEVIATION_COUNT), 0) AS AVG_MTBD
FROM RAW.CCP_READINGS
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.DEVIATION_CAUSES
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ROOT_CAUSE, SUM(HOLD_HOURS) AS HOLD_HOURS,
       SUM(DEVIATION_COUNT) AS DEVIATION_COUNT
FROM RAW.CCP_READINGS
WHERE DEVIATION_COUNT > 0
GROUP BY ROOT_CAUSE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(OPERATING_HOURS) AS OPERATING_HOURS, SUM(PLANNED_HOURS) AS PLANNED_HOURS,
         SUM(DEVIATION_COUNT) AS FAILURES, MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.CCP_READINGS
), network AS (SELECT COUNT(*) AS LINE_COUNT FROM RAW.PROCESSING_LINES),
kits AS (
  SELECT SUM(ON_ORDER_QTY) AS ON_ORDER_QTY,
         100.0 * SUM(LEAST(ON_HAND_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT
  FROM RAW.VERIFICATION_KITS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Line Availability' AS TITLE,
         100.0 * OPERATING_HOURS / NULLIF(PLANNED_HOURS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'CCP Deviations', FAILURES, '' FROM observations
  UNION ALL SELECT 3, 'Hours Between Deviations', OPERATING_HOURS / NULLIF(FAILURES, 0), ' hrs' FROM observations
  UNION ALL SELECT 4, 'Lines Monitored', LINE_COUNT, '' FROM network
  UNION ALL SELECT 6, 'Kits on Order', ON_ORDER_QTY, '' FROM kits
  UNION ALL SELECT 7, 'Verification Kit Coverage', COVERAGE_PCT, '%' FROM kits
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1)) || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.DEVIATION_CAUSES SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
